import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { loadEnvFile } from 'node:process';

const envFile = new URL('../.env', import.meta.url);

if (existsSync(envFile)) {
  loadEnvFile(envFile);
}

const baseUrl = process.env['API_BASE_URL']?.trim();

if (!baseUrl) {
  throw new Error('API_BASE_URL is required. Copy .env.example to .env and set API_BASE_URL.');
}

const outputDirectory = new URL('../src/environments/', import.meta.url);
mkdirSync(outputDirectory, { recursive: true });
writeFileSync(
  new URL('environment.ts', outputDirectory),
  `// Generated by scripts/generate-env.mjs. Edit .env to change this value.\nexport const environment = ${JSON.stringify({ apiBaseUrl: baseUrl }, null, 2)};\n`,
);
